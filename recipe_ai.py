import os
from dotenv import load_dotenv

from google import genai
from google.genai import types

from format import Recipe

MODELS = [
    "gemini-3.5-flash-lite",
    "gemini-3.1-flash-lite"
]

load_dotenv()

client = genai.Client(
    api_key=os.getenv("GEMINI_API_KEY")
)

def extract_recipe(caption):
    prompt = f"""
다음은 인스타그램 요리 게시물의 캡션이다.

캡션에서 레시피 정보를 추출하여 요리 초보자도 이해하기 쉬운 형태로 정리하라.

## 기본 원칙

- 캡션에 포함된 레시피 정보를 기준으로 작성한다.
- 원본 레시피의 의미와 조리 순서를 변경하지 않는다.
- 캡션에 없는 새로운 재료나 새로운 조리 방법을 원본 레시피에 임의로 추가하지 않는다.
- 캡션에 명시된 정보와 AI가 추정하거나 변경한 정보를 명확하게 구분한다.
- AI가 재료의 양을 추정한 경우 반드시 estimated를 true로 설정한다.
- 원본 정보는 절대로 덮어쓰지 않고 original_amount에 보존한다.
- 정보가 부족하여 합리적인 추정이 어려운 경우 억지로 숫자를 만들어내지 않는다.


## 음식 이름

- 캡션에서 음식 이름을 추출한다.
- 음식 이름을 임의로 변경하거나 새로운 이름을 만들어내지 않는다.


## 음식 카테고리

음식의 종류와 조리 특성을 기준으로 분류 태그를 생성한다.

- 캡션에 있는 해시태그를 그대로 복사하지 않는다.
- 캡션의 해시태그를 tags의 값으로 직접 사용하지 않는다.
- 음식의 이름, 재료, 조리법을 종합하여 음식의 대표적인 카테고리를 판단한다.
- tags에는 음식의 분류를 나타내는 일반적인 단어만 작성한다.
- 음식의 고유한 이름이나 상품명, 유행어, 상황을 나타내는 단어는 작성하지 않는다.
- "집밥", "신혼밥상", "다이어트", "간단요리"와 같은 상황이나 홍보성 태그는 작성하지 않는다.
- 가장 대표적인 카테고리 1~2개만 작성한다.
- tags에는 "#" 기호를 포함하지 않는다.

예:
음식 이름: 불닭 크림 리조또

올바른 예:
"tags": ["양식", "리조또"]

잘못된 예:
"tags": ["불닭리조또", "크림리조또", "집밥", "신혼밥상"]

음식 이름: 김치찌개

올바른 예:
"tags": ["한식", "찌개"]

음식 이름: 크림 파스타

올바른 예:
"tags": ["양식", "파스타"]

## 인분

- 캡션에 명시된 인분을 사용한다.
- 인분이 명시되어 있지 않다면 임의로 추정하지 않는다.


## 재료

각 재료에 대해 다음 정보를 작성한다.


### name

재료의 이름을 작성한다.


### original_amount

캡션에 적혀 있는 원래 양 또는 양에 대한 표현을 그대로 작성한다.

예:
- "참치 135g" → "135g"
- "후추 적당량" → "적당량"
- "불닭소스 취향껏" → "취향껏"


### amount

요리 초보자가 실제 조리에 사용할 수 있도록 가능한 경우 구체적인 양으로 작성한다.

다음과 같이 양이 추상적으로 표현된 경우 일반적인 요리 기준을 바탕으로 합리적인 범위에서 구체적인 양을 추정할 수 있다.

- 적당량
- 약간
- 조금
- 적당히
- 취향껏

가능하면 다음과 같이 조리에 바로 사용할 수 있는 단위로 표현한다.

- g
- ml
- 큰술
- 작은술
- 개
- 장
- 줄
- 마리
- 꼬집
- 컵

예:

- 원본: "후추 적당량"
  → amount: "2~3꼬집"

- 원본: "파슬리 적당량"
  → amount: "1작은술"

- 원본: "불닭소스 취향껏"
  → amount: "1~2큰술"

- 원본: "양파 적당량"
  → amount: "1/4개"


### AI 추정값에 대한 규칙

- amount는 가능한 경우 추상적인 표현보다 구체적인 양을 우선한다.
- AI가 일반적인 요리 기준을 바탕으로 합리적인 양을 추정할 수 있다면 구체적인 양으로 변환한다.
- 추정값은 지나치게 정밀한 숫자를 사용하지 않는다.
- 필요한 경우 "1~2큰술", "2~3꼬집", "5~6마리"와 같이 범위로 표현한다.
- 원본에 근거가 부족한 경우 억지로 정확한 숫자를 만들어내지 않는다.
- 합리적인 추정이 불가능하다면 원래 표현을 그대로 유지한다.
- 개인의 취향에 따라 양이 크게 달라지는 재료는 지나치게 정확한 수치를 만들어내지 않는다.
- AI가 추정한 양은 반드시 estimated=true로 표시한다.


### estimated

amount가 캡션의 원래 양과 동일하면 false로 설정한다.

AI가 원본에 없는 구체적인 양을 추정하거나 원본의 추상적인 표현을 구체적인 양으로 변경했다면 true로 설정한다.

예:

원본:
"후추 적당량"

amount:
"2~3꼬집"

estimated:
true


원본:
"참치 135g"

amount:
"135g"

estimated:
false


원본:
"불닭소스 취향껏"

amount:
"1~2큰술"

estimated:
true


원본:
"양파 적당량"

합리적인 추정이 어려운 경우:

amount:
"적당량"

estimated:
false


## 대체 가능한 재료

레시피에 포함된 재료 중 다른 재료로 대체할 수 있는 재료를 별도로 작성한다.

이 정보는 원본 레시피의 재료를 변경하는 것이 아니라 사용자가 해당 재료를 가지고 있지 않을 때 참고할 수 있는 대체 방법이다.

### 기본 규칙

- ingredients에 실제로 포함된 재료만 대체 대상으로 선택한다.
- 모든 재료에 대해 대체 재료를 제시할 필요는 없다.
- 각 재료에 대해 가장 적절한 대체 방법 하나만 제시한다.
- 대체 재료는 일반적인 요리 지식에 근거하여 판단한다.
- 일반 가정에서 구하기 쉬운 재료를 우선적으로 사용한다.
- 대체했을 때 요리의 맛이나 조리 결과가 크게 달라질 가능성이 높은 경우 무리하게 제시하지 않는다.
- 대체가 적절하지 않은 재료는 포함하지 않는다.
- 대체 재료의 특성과 원래 재료의 용도를 고려하여 적절한 양으로 조정한다.
- 대체 재료는 하나의 재료일 수도 있고 여러 재료의 조합일 수도 있다.
- 여러 재료의 조합이 필요한 경우 alternative에 재료들을 "+ "로 연결하여 작성한다.
- 여러 재료의 조합을 사용하는 경우 alternative_amount에도 각 재료의 양을 함께 작성한다.
- AI가 판단하여 생성한 대체 재료와 대체량은 estimated=true로 설정한다.
- 대체 재료나 대체량을 합리적으로 판단하기 어려운 경우 해당 대체 재료를 제시하지 않는다.
- 대체 가능한 재료가 없다면 substitutions는 빈 배열 []로 반환한다.
- original에는 ingredients에 있는 원래 재료의 이름을 그대로 작성한다.
- original_amount에는 ingredients에 있는 원래 재료의 양을 그대로 작성한다.
- alternative에는 원래 재료를 대신하여 사용할 수 있는 대체 재료 또는 대체 재료의 조합을 작성한다.
- alternative_amount에는 대체 재료를 실제 조리에 사용할 때 필요한 양을 작성한다.
- substitutions는 원본 레시피의 ingredients나 steps를 변경하지 않는다.
- substitutions에 새로운 재료가 포함되더라도 이는 원본 레시피에 추가하는 재료가 아니라 원래 재료를 대신하기 위한 대체 재료를 의미한다.


### 예시

원본 재료:
생크림 200ml

대체:
  "original": "생크림",
  "original_amount": "200ml",
  "alternative": "우유 + 버터",
  "alternative_amount": "우유 180ml + 버터 20g",
  "estimated": true


원본 재료:
치킨스톡 1큰술

대체:
  "original": "치킨스톡",
  "original_amount": "1큰술",
  "alternative": "연두",
  "alternative_amount": "1큰술",
  "estimated": true


대체가 적절하지 않은 재료:

  "substitutions": []

## 조리 순서

각 조리 단계에 대해 두 가지 표현을 작성한다.


### original

캡션에 적힌 조리 과정을 최대한 원문에 가깝게 작성한다.

단, 이모지, 해시태그, 불필요한 감탄 표현 등 레시피 내용과 관계없는 부분은 제거할 수 있다.


### simplified

원문을 그대로 복사하지 말고 요리 초보자가 이해하기 쉽도록 자연스럽고 간결한 문장으로 다시 작성한다.

조리 과정의 의미와 순서는 반드시 유지한다.

예:

원본:
"물 50ml 넣고 살짝 저어주기"

변환:
"물 50ml를 넣고 저어준다."


원본:
"계란 2개 넣어서 뚜껑덮고 약불에 1분 30초 끓이면 끝!"

변환:
"계란 2개를 넣고 뚜껑을 덮은 뒤 약불에서 1분 30초간 끓인다."


## 조리 과정에서 반드시 지킬 규칙

- 원문을 단순히 복사하지 말고 자연스러운 문장으로 작성한다.
- 조리법은 반드시 '-다' 체로 작성한다.
- '~합니다', '~해요', '~해주세요' 등의 존댓말은 사용하지 않는다.
- 예: "양파를 넣어줍니다." → "양파를 넣는다."
- 예: "볶아주세요." → "볶는다."
- 이모지와 해시태그를 제거한다.
- 불필요한 감탄 표현이나 말투는 제거한다.
- 원문에 없는 조리 방법을 추가하지 않는다.
- 원문에 없는 시간이나 온도를 추가하지 않는다.
- 원문에 없는 불의 세기나 조리 도구를 추가하지 않는다.
- 원문의 조리 순서를 변경하지 않는다.
- 원문에 있는 시간, 온도, 불의 세기, 조리 방법 등의 정보는 그대로 유지한다.
- 원문의 의미를 더 명확하게 표현할 수는 있지만 새로운 사실을 추가해서는 안 된다.
- 조리 단계에서 재료의 양을 새롭게 추정하거나 변경하지 않는다.
- 재료의 양에 대한 추정은 ingredients의 amount에서만 처리한다.


## 출력 규칙

반드시 지정된 JSON Schema에 맞는 JSON만 반환한다.

설명, 주석, 마크다운, 코드 블록 등 JSON 이외의 내용을 추가하지 않는다.

## 캡션

{caption}
"""

    for model in MODELS:
        try:
            response = client.models.generate_content(
                model=model,
                contents=prompt,
                config=types.GenerateContentConfig(
                    response_mime_type="application/json",
                    response_schema=Recipe,
                ),
            )

            return Recipe.model_validate_json(response.text)

        except Exception as e:
            if "503" in str(e):
                continue

            raise